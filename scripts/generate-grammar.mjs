// Generates syntaxes/gherkin.tmLanguage.json from data/gherkin-languages.json (cucumber/gherkin).
// The keywords of every dialect are merged, so a file highlights correctly whatever its
// `# language:` header. Usage: node scripts/generate-grammar.mjs [--check]
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const dialects = JSON.parse(readFileSync(`${root}data/gherkin-languages.json`, "utf8"));
const output = `${root}syntaxes/gherkin.tmLanguage.json`;

const SECTIONS = ["feature", "background", "rule", "scenario", "scenarioOutline", "examples"];
const STEPS = ["given", "when", "then", "and", "but"];

function keywords(keys) {
  const all = new Set();
  for (const dialect of Object.values(dialects)) {
    for (const key of keys) {
      for (const keyword of dialect[key]) {
        all.add(keyword);
      }
    }
  }
  return [...all];
}

const escape = (text) => text.replace(/[.*+?^${}()|[\]\\/]/g, "\\$&");

// Longest first, so that e.g. "Scenario Outline" wins over "Scenario".
const alternation = (words) =>
  [...words]
    .sort((a, b) => b.length - a.length || a.localeCompare(b))
    .map(escape)
    .join("|");

const sectionKeywords = alternation(keywords(SECTIONS));
// Step keywords keep their trailing space where the language needs one ("Given "), and have none
// where it does not ("假如"); the universal "* " is listed by every dialect.
const stepKeywords = alternation(keywords(STEPS));

const grammar = {
  $schema: "https://raw.githubusercontent.com/martinring/tmlanguage/master/tmlanguage.json",
  name: "Gherkin",
  scopeName: "text.gherkin.cukebench",
  comment: `Generated by scripts/generate-grammar.mjs from data/gherkin-languages.json; do not edit.`,
  patterns: [
    { include: "#language" },
    { include: "#comment" },
    { include: "#tags" },
    { include: "#section" },
    { include: "#step" },
    { include: "#docString" },
    { include: "#table" },
  ],
  repository: {
    language: {
      match: "^\\s*(#)\\s*(language)\\s*(:)\\s*([\\w-]+)\\s*$",
      captures: {
        1: { name: "comment.line.number-sign.gherkin punctuation.definition.comment.gherkin" },
        2: { name: "keyword.other.language.gherkin" },
        3: { name: "punctuation.separator.key-value.gherkin" },
        4: { name: "constant.language.dialect.gherkin" },
      },
    },
    comment: {
      match: "^\\s*(#).*$",
      name: "comment.line.number-sign.gherkin",
      captures: { 1: { name: "punctuation.definition.comment.gherkin" } },
    },
    tags: {
      match: "(?<=^|\\s)@[^\\s@#]+",
      name: "entity.name.tag.gherkin",
    },
    section: {
      match: `^\\s*(${sectionKeywords})\\s*(:)(.*)$`,
      captures: {
        1: { name: "keyword.control.section.gherkin" },
        2: { name: "punctuation.separator.key-value.gherkin" },
        3: { name: "entity.name.section.gherkin", patterns: [{ include: "#parameter" }] },
      },
    },
    step: {
      begin: `^\\s*(${stepKeywords})`,
      beginCaptures: { 1: { name: "keyword.control.step.gherkin" } },
      end: "$",
      contentName: "string.unquoted.step.gherkin",
      patterns: [{ include: "#parameter" }, { include: "#quoted" }, { include: "#number" }],
    },
    parameter: {
      match: "<[^<>\\n]+>",
      name: "variable.parameter.outline.gherkin",
    },
    quoted: {
      patterns: [
        { match: '"[^"\\n]*"', name: "string.quoted.double.gherkin" },
        { match: "'[^'\\n]*'", name: "string.quoted.single.gherkin" },
      ],
    },
    number: {
      match: "(?<![\\w.])-?\\d+(?:\\.\\d+)?(?![\\w.])",
      name: "constant.numeric.gherkin",
    },
    docString: {
      patterns: [
        {
          begin: '^\\s*(""")(\\S*)\\s*$',
          beginCaptures: {
            1: { name: "punctuation.definition.string.begin.gherkin" },
            2: { name: "entity.name.type.media-type.gherkin" },
          },
          end: '^\\s*(""")\\s*$',
          endCaptures: { 1: { name: "punctuation.definition.string.end.gherkin" } },
          contentName: "string.unquoted.block.gherkin",
        },
        {
          begin: "^\\s*(```)(\\S*)\\s*$",
          beginCaptures: {
            1: { name: "punctuation.definition.string.begin.gherkin" },
            2: { name: "entity.name.type.media-type.gherkin" },
          },
          end: "^\\s*(```)\\s*$",
          endCaptures: { 1: { name: "punctuation.definition.string.end.gherkin" } },
          contentName: "string.unquoted.block.gherkin",
        },
      ],
    },
    table: {
      begin: "^\\s*(?=\\|)",
      end: "$",
      patterns: [
        { match: "\\\\[|n\\\\]", name: "constant.character.escape.gherkin" },
        { match: "\\|", name: "punctuation.separator.table.gherkin" },
        { include: "#parameter" },
        { match: "[^|\\\\<]+|<", name: "string.unquoted.table.cell.gherkin" },
      ],
    },
  },
};

const text = `${JSON.stringify(grammar, null, 2)}\n`;
if (process.argv.includes("--check")) {
  if (readFileSync(output, "utf8") !== text) {
    console.error("syntaxes/gherkin.tmLanguage.json is out of date: run npm run generate");
    process.exit(1);
  }
} else {
  writeFileSync(output, text);
}
